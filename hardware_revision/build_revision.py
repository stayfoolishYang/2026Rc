"""Produce an isolated, pin-compatible EasyEDA revision; never edit source."""
import copy
import hashlib
import json
import math
from collections import Counter
from shapely.geometry import LineString, Point
from inspect_geometry import ROOT, SOURCE, load_geometry

OUT = ROOT / 'hardware_revision' / '2026Rc_R1b_power.epro'
archive, pcb_path, pcb, objects, pads = load_geometry()
original = copy.deepcopy(pcb)
project = json.loads(archive.read('project.json'))
project['config']['title'] = '2026Rc_R1b_power'
project['boards'] = {'Board1': {
    'schematic': next(iter(project['schematics'])),
    'pcb': next(iter(project['pcbs'])),
}}

next_id = max(int(r[1][1:]) for r in pcb if len(r)>1 and isinstance(r[1], str) and r[1].startswith('e') and r[1][1:].isdigit()) + 1
def new_id():
    global next_id
    result = 'e' + str(next_id)
    next_id += 1
    return result

targets = {'12V':80, '7.4V':60, '5V':50, '$1N1669':60}
choices = [80, 60, 50, 40, 30, 25, 23]
changes = []
result = []
for r in pcb:
    # Derived copper and teardrops must be regenerated by the native editor.
    if r[0] in ('POURED', 'TEARDROP', 'CONNECT'):
        continue
    if r[0] == 'LINE' and r[3] in targets:
        start, end = (r[5], r[6]), (r[7], r[8])
        length = math.dist(start, end)
        n = max(1, math.ceil(length/10))
        other = [g for name, net, layers, g in objects if r[4] in layers and net != r[3]]
        groups = []
        for i in range(n):
            p = tuple(start[j] + (end[j]-start[j])*i/n for j in range(2))
            q = tuple(start[j] + (end[j]-start[j])*(i+1)/n for j in range(2))
            segment = LineString([p, q])
            allowed = 2*(min(segment.distance(g) for g in other)-8.1)
            width = max([r[9]] + [v for v in choices if r[9] <= v <= targets[r[3]] and v <= allowed])
            if groups and groups[-1][2] == width:
                groups[-1][1] = q
            else:
                groups.append([p, q, width])
        for i, (p, q, width) in enumerate(groups):
            row = copy.deepcopy(r)
            row[1] = r[1] if i == 0 else new_id()
            row[5:10] = [round(p[0], 6), round(p[1], 6), round(q[0], 6), round(q[1], 6), width]
            result.append(row)
        changes.append({'id':r[1], 'net':r[3], 'old_width_mil':r[9], 'segments': [{'length_mm':round(math.dist(p,q)*.0254,3),'width_mil':v} for p,q,v in groups]})
    elif r[0] == 'VIA' and r[3] == '7.4V':
        row = copy.deepcopy(r)
        other = [g for name, net, layers, g in objects if net != r[3]]
        clearance = min(Point(r[5],r[6]).distance(g) for g in other)
        diameter = max([r[8]] + [v for v in (32,40,48) if v/2+8.1 <= clearance])
        row[8] = diameter
        row[7] = 20 if diameter >=40 else r[7]
        changes.append({'via':r[1], 'old_drill_pad_mil':[r[7],r[8]], 'new_drill_pad_mil':[row[7],row[8]]})
        result.append(row)
    else:
        result.append(r)

# Native DRC feedback: board-edge clearance is 11.8 mil. These pieces
# follow the right edge at x=-35 mil and require narrower copper.
native_fixes = {k:40 for k in ('e192','e193','e194','e867','e869','e871','e873','e874')}
# Both adjacent power nets were widened: reduce the 12V piece to restore spacing.
native_fixes['e344'] = 60
for row in result:
    if row[0] == 'LINE' and row[1] in native_fixes:
        changes.append({'native_drc_fix':row[1], 'from_width_mil':row[9], 'to_width_mil':native_fixes[row[1]]})
        row[9] = native_fixes[row[1]]

# Preserve board geometry, every component, and every numbered pin assignment.
for kind in ('COMPONENT','PAD_NET','POLY','ATTR'):
    assert [r for r in result if r[0]==kind] == [r for r in original if r[0]==kind], kind
# Silk version near the existing date; retain team and date.
date = next(r for r in result if r[0]=='STRING' and r[6]=='2026年8月')
date[6] = '2026.09 R1'

def widths(rows):
    out={}
    for r in rows:
        if r[0]=='LINE' and r[3] in targets:
            key=str(r[9])
            entry=out.setdefault(r[3],{})
            entry[key]=entry.get(key,0)+math.hypot(r[7]-r[5],r[8]-r[6])*.0254
    return {net:{w:round(length,2) for w,length in values.items()} for net,values in out.items()}

payload = ('\n'.join(json.dumps(r,ensure_ascii=False,separators=(',',':')) for r in result)+'\n').encode('utf-8')
import zipfile
with zipfile.ZipFile(OUT,'w',zipfile.ZIP_DEFLATED) as dest:
    for entry in archive.infolist():
        data=archive.read(entry.filename)
        if entry.filename==pcb_path: data=payload
        if entry.filename=='project.json': data=json.dumps(project,ensure_ascii=False,indent=2).encode('utf-8')
        dest.writestr(entry.filename,data)
report={'source':str(SOURCE),'source_sha256':hashlib.sha256(SOURCE.read_bytes()).hexdigest(), 'output':str(OUT), 'old_width_length_mm':widths(original),'new_width_length_mm':widths(result),'changes':changes,'native_validation':'PENDING - repour and DRC required','limitations':['No current rating claimed: load/module specifications unknown','No added protection or limit circuit; requires separate hardware and firmware design']}
(OUT.parent/'revision_manifest.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
print(json.dumps({k:report[k] for k in ['output','old_width_length_mm','new_width_length_mm']},ensure_ascii=False,indent=2))
